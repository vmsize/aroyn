import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {createRuntime, folder} from './runtime.mjs';
import {seedRecovery, hash} from './recovery-fixture.mjs';
import {initializeDeletionLedger, deletionManifestFromLedger} from '../tools/deletion-ledger-recovery.mjs';
import {recordDeletion, pruneDeletionLedger} from '../workers/shared/deletion-ledger.js';
import {recoveryStep} from '../tools/recovery-sanitizer.mjs';
import {newRetentionCycle, retentionStep} from '../workers/shared/retention-runner.js';
import {localMutationNamespace} from './mutation-helpers.mjs';

const runtime = await createRuntime({mock: true, apiBindings: {DELETION_LEDGER_MODE: 'required'}});
let restored;
const results = [];
const pass = name => {results.push({name, pass: true}); console.log('PASS ' + name);};
const DAY = 86400000;
try {
  const bucket = await runtime.mf.getR2Bucket('DELETION_LEDGER', 'api');
  const payloads = await runtime.mf.getR2Bucket('PAYLOADS', 'api');
  const env = {DELETION_LEDGER_MODE: 'required', DELETION_LEDGER: bucket};
  const seeded = await seedRecovery({DB: runtime.db, PAYLOADS: payloads});
  const [a, b] = seeded.accounts;
  const deletion = () => runtime.api.fetch('http://local/api/v2/account/delete', {method: 'POST', headers: {authorization: 'Bearer ' + a.token, 'content-type': 'application/json'}, body: JSON.stringify({confirmation: 'DELETE'})});
  const unavailable = await deletion();
  assert.equal(unavailable.status, 503);
  assert.equal((await unavailable.json()).code, 'DELETION_LEDGER_UNAVAILABLE');
  assert(await runtime.db.prepare('SELECT id FROM users WHERE id=?1').bind(a.id).first());
  assert.equal((await runtime.db.prepare('SELECT COUNT(*) n FROM account_deletions').first()).n, 0);
  assert.equal((await runtime.api.fetch('http://local/api/v2/auth/me', {headers: {authorization: 'Bearer ' + a.token}})).status, 200);
  pass('required uninitialized ledger returns 503 before DB revocation or deletion');
  await assert.rejects(initializeDeletionLedger(bucket, {accessClosed: false, oldWritersDrained: true}));
  await assert.rejects(initializeDeletionLedger(bucket, {accessClosed: true, oldWritersDrained: false}));
  const meta = await initializeDeletionLedger(bucket, {accessClosed: true, oldWritersDrained: true});
  await assert.rejects(initializeDeletionLedger(bucket, {accessClosed: true, oldWritersDrained: true}));
  pass('operator initialization requires closed drained cutover and never replaces existing coverage');
  const backupAt = Date.now();
  const tables = (await runtime.db.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_cf_%' ORDER BY CASE WHEN name='users' THEN 0 ELSE 1 END,name").all()).results.map(r => r.name);
  const backup = [];
  for (const table of tables) backup.push({table, rows: (await runtime.db.prepare('SELECT * FROM ' + table).all()).results});
  const deleted = await deletion(); assert.equal(deleted.status, 200);
  assert.equal(await runtime.db.prepare('SELECT id FROM users WHERE id=?1').bind(a.id).first(), null);
  assert.equal((await runtime.db.prepare('SELECT COUNT(*) n FROM account_deletions').first()).n, 0);
  const original = await (await bucket.get('events/' + a.id + '.json')).json();
  assert.deepEqual(Object.keys(original).sort(), ['requestedAt', 'userId']);
  assert.equal(original.userId, a.id);
  pass('completed HTTP deletion keeps minimal independent record after D1 deletion job disappears');
  const retries = await Promise.all(Array.from({length: 8}, () => recordDeletion(env, a.id)));
  for (const result of retries) assert.deepEqual(result, original);
  assert.equal((await bucket.list({prefix: 'events/'})).objects.length, 1);
  // A new account has a new ID. Ledger lookup is never by Discord ID.
  const newId = 'usr_new_after_delete';
  await runtime.db.prepare('INSERT INTO users(id,discord_id,discord_username,created_at,updated_at,last_login_at) VALUES(?1,?2,?3,?4,?4,?4)').bind(newId, '900001', 'same-discord-new-profile', Date.now()).run();
  const newToken = 'VS_ledger_new_profile';
  await runtime.db.prepare('INSERT INTO web_sessions VALUES(?1,?2,?3,?4)').bind(await hash(newToken), newId, Date.now(), Date.now() + DAY).run();
  assert.equal((await runtime.api.fetch('http://local/api/v2/auth/me', {headers: {authorization: 'Bearer ' + newToken}})).status, 200);
  pass('concurrent retries preserve first timestamp; same Discord identity can use a new empty profile');
  await assert.rejects(recordDeletion({...env, DELETION_LEDGER: {get: bucket.get.bind(bucket), put: async () => {throw new Error('fixture put failure');}}}, 'usr_failed_write'));
  assert.equal(await bucket.get('events/usr_failed_write.json'), null);
  const beforeSize = (await bucket.list()).objects.length;
  await assert.rejects(recordDeletion(env, '../unsafe'));
  assert.equal((await bucket.list()).objects.length, beforeSize);
  pass('failed writes and invalid IDs fail closed without storing an event');
  const context = {backupAt, frozenAt: Date.now(), isolatedDestination: true, apiAccessClosed: true, liveAccessClosed: true, freshDurableObjects: true, signingSecretsRotated: true};
  const options = {ledgerCleanupPaused: true, expectedLedgerId: meta.ledgerId};
  await assert.rejects(deletionManifestFromLedger(bucket, {...context, backupAt: meta.startedAt - 1}, options));
  await assert.rejects(deletionManifestFromLedger(bucket, context, {...options, ledgerCleanupPaused: false}));
  await assert.rejects(deletionManifestFromLedger(bucket, context, {...options, expectedLedgerId: 'wrong-bucket'}));
  await assert.rejects(deletionManifestFromLedger(bucket, {...context, apiAccessClosed: false}, options));
  const manifest = await deletionManifestFromLedger(bucket, context, options);
  assert.deepEqual(manifest.deletions, [original]);
  pass('manifest comes from preserved ledger; old coverage, wrong bucket, live access or unpaused cleanup are rejected');
  restored = await createRuntime({mock: true});
  for (const {table, rows} of backup) for (const row of rows) {
    const columns = Object.keys(row);
    await restored.db.prepare(`INSERT INTO ${table}(${columns.join(',')}) VALUES(${columns.map(() => '?').join(',')})`).bind(...Object.values(row)).run();
  }
  assert(await restored.db.prepare('SELECT id FROM users WHERE id=?1').bind(a.id).first());
  const recoveryEnv = {DB: restored.db, PAYLOADS: await restored.mf.getR2Bucket('PAYLOADS', 'api'), SNAPSHOT_STORAGE: await restored.mf.getDurableObjectNamespace('SNAPSHOT_STORAGE', 'api'), STATS_CACHE: await restored.mf.getDurableObjectNamespace('STATS_CACHE', 'api')};
  recoveryEnv.RUNTIME_MUTATIONS=localMutationNamespace(recoveryEnv);
  let state; let rounds = 0;
  do {state = await recoveryStep(recoveryEnv, manifest, context, state);} while (!state.sanitized && ++rounds < 100);
  assert(state.sanitized); assert.equal(state.reopenAllowed, false);
  assert.equal(await restored.db.prepare('SELECT id FROM users WHERE id=?1').bind(a.id).first(), null);
  assert(await restored.db.prepare('SELECT id FROM users WHERE id=?1').bind(b.id).first());
  assert(await restored.db.prepare('SELECT session_id FROM analytics_sessions WHERE session_id=?1').bind(b.sid).first());
  assert(await bucket.get('events/' + a.id + '.json'));
  pass('independently read ledger removes resurrected profile from restored DB while other profile/history survive');
  const firstWrites = await Promise.all(Array.from({length: 8}, () => recordDeletion(env, 'usr_concurrent_first')));
  for (const event of firstWrites) assert.deepEqual(event, firstWrites[0]);
  const pendingBeforeCutover = await recordDeletion(env, 'usr_pending_before_cutover', meta.startedAt - 1);
  assert.equal(pendingBeforeCutover.requestedAt, meta.startedAt);
  // Age this fixture only, retaining first record's timestamp. No real clock,
  // real personal data or provider lifecycle configuration is changed.
  const future = original.requestedAt + 36 * DAY;
  await assert.rejects(deletionManifestFromLedger(bucket, context, {...options, now: future}));
  const old = await pruneDeletionLedger(env, {now: future}); assert.equal(old.removed, 3);
  assert.equal(await bucket.get('events/' + a.id + '.json'), null);
  assert(await bucket.get('coverage.json'));
  pass('35-day coverage excludes older backups; expired record is removed without resetting coverage');
  for (let i = 0; i < 63; i++) await bucket.put(`events/usr_expired_${String(i).padStart(3, '0')}.json`, JSON.stringify({userId: `usr_expired_${String(i).padStart(3, '0')}`, requestedAt: meta.startedAt}));
  const fresh = {userId: 'usr_fresh', requestedAt: future};
  await bucket.put('events/usr_fresh.json', JSON.stringify(fresh));
  let cursor; let removed = 0; let pages = 0;
  do {const page = await pruneDeletionLedger(env, {now: future, cursor}); assert(page.visited <= 25); removed += page.removed; cursor = page.cursor; pages++;} while (cursor);
  assert.equal(removed, 63); assert.equal(pages, 3);
  assert.deepEqual(await (await bucket.get('events/usr_fresh.json')).json(), fresh);
  pass('63-record expiry uses three bounded pages and keeps a fresh event');
  await bucket.put('events/usr_corrupt.json', JSON.stringify({userId: 'different', requestedAt: future}));
  await assert.rejects(pruneDeletionLedger(env, {now: future}));
  const recentContext = {...context, backupAt: future - DAY, frozenAt: future};
  await assert.rejects(deletionManifestFromLedger(bucket, recentContext, {...options, now: future}));
  await bucket.delete('events/usr_corrupt.json');
  const stalledBucket = {get: bucket.get.bind(bucket), list: async () => ({objects: [], truncated: true, cursor: 'stalled'})};
  await assert.rejects(pruneDeletionLedger({...env, DELETION_LEDGER: stalledBucket}, {now: future, cursor: 'stalled'}));
  pass('corrupt entries and non-advancing pages block recovery or maintenance rather than claiming completeness');
  const maintenanceEnv = {...env, ...recoveryEnv};
  await bucket.put('events/usr_maintenance_old.json', JSON.stringify({userId: 'usr_maintenance_old', requestedAt: meta.startedAt}));
  let cycle = newRetentionCycle(future); let steps = 0;
  while (cycle.active && steps++ < 100) cycle = await retentionStep(maintenanceEnv, cycle);
  assert.equal(cycle.active, false); assert.equal(cycle.ledgerRemoved, 1);
  assert(await bucket.get('events/usr_fresh.json'));
  pass('ordinary retention cycle includes bounded journal cleanup with a saved phase');
  assert.deepEqual(await recordDeletion({}, 'usr_disabled'), null);
  assert.deepEqual(await pruneDeletionLedger({}), {done: true, cursor: null, removed: 0, visited: 0});
  pass('prepared feature remains inactive until explicitly enabled during controlled cutover');
  await writeFile(resolve(folder, 'deletion-ledger-results.json'), JSON.stringify({source: 'isolated Miniflare D1/R2/DO; synthetic identities; no cloud cutover', results}, null, 2));
} finally {await runtime.mf.dispose(); if (restored) await restored.mf.dispose();}
